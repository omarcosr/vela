/**
 * phpMyAdmin, installed on demand into <root>/data/phpmyadmin and served as a site
 * (phpmyadmin.localhost, or pma.localhost when the user already has a "phpmyadmin" site).
 * config.inc.php points at Vela's MariaDB on 127.0.0.1 (never "localhost": see mariaDbBind) and
 * is regenerated while it carries the Vela marker; the blowfish secret survives regeneration.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { join, normalize, resolve } from "node:path";
import { dataDir, tmpDir, type Config, type SiteConfig } from "./config";
import { download, unzip } from "./download";

const URL = "https://www.phpmyadmin.net/downloads/phpMyAdmin-latest-english.zip";
const MARKER = "// Generated by Vela. Remove this line to keep your own edits.";
const LEGACY_ADMINER = "adminer";

export const pmaDir = (cfg: Config) => dataDir(cfg.root, "phpmyadmin");
const same = (a: string, b: string) => normalize(resolve(a)).toLowerCase() === normalize(resolve(b)).toLowerCase();

/** The site serving Vela's phpMyAdmin, if registered. */
export function pmaSite(cfg: Config): SiteConfig | undefined {
  return cfg.sites.find((s) => same(s.path, pmaDir(cfg)));
}

/** Forget the Adminer site older Vela builds registered (its files are left alone). True when it changed. */
export function dropLegacyAdminer(cfg: Config): boolean {
  const before = cfg.sites.length;
  cfg.sites = cfg.sites.filter((s) => !(s.name === LEGACY_ADMINER && same(s.path, dataDir(cfg.root, "adminer"))));
  return cfg.sites.length !== before;
}

const phpStr = (v: string) => "'" + v.replace(/\\/g, "\\\\").replace(/'/g, "\\'") + "'";

function writeConfig(cfg: Config, dir: string): void {
  const path = join(dir, "config.inc.php");
  let secret = "";
  if (existsSync(path)) {
    const cur = readFileSync(path, "utf8");
    if (!cur.includes(MARKER)) return; // the user took it over
    secret = /\['blowfish_secret'\]\s*=\s*'([^']{32})'/.exec(cur)?.[1] ?? "";
  }
  // sodium needs exactly 32 bytes
  if (!secret) secret = randomBytes(24).toString("base64").replace(/[^A-Za-z0-9]/g, "x").padEnd(32, "x").slice(0, 32);
  mkdirSync(join(dir, "tmp"), { recursive: true });
  const php = `<?php
${MARKER}
declare(strict_types=1);
$cfg['blowfish_secret'] = ${phpStr(secret)};
$i = 1;
$cfg['Servers'][$i]['verbose'] = 'Vela MariaDB';
$cfg['Servers'][$i]['auth_type'] = 'cookie';
$cfg['Servers'][$i]['host'] = '127.0.0.1';
$cfg['Servers'][$i]['port'] = ${phpStr(String(cfg.services.mariadb.port))};
$cfg['Servers'][$i]['compress'] = false;
$cfg['Servers'][$i]['AllowNoPassword'] = true;
$cfg['TempDir'] = ${phpStr(join(dir, "tmp").replace(/\\/g, "/"))};
$cfg['VersionCheck'] = false;
$cfg['SendErrorReports'] = 'never';
`;
  writeFileSync(path, php, "utf8");
}

let installing: Promise<void> | null = null;

/** True while the first download/extract runs. */
export const pmaInstalling = () => installing !== null;

/** Download phpMyAdmin once, (re)write its config for the current MariaDB port and register the site. */
export async function ensurePhpMyAdmin(cfg: Config): Promise<SiteConfig> {
  const dir = pmaDir(cfg);
  // concurrent calls (repeated clicks) share one download instead of racing on the same .part
  if (!existsSync(join(dir, "index.php"))) {
    installing ??= installPma(cfg, dir).finally(() => (installing = null));
    await installing;
  }
  writeConfig(cfg, dir);
  dropLegacyAdminer(cfg);
  let site = pmaSite(cfg);
  if (!site) {
    const name = cfg.sites.some((s) => s.name === "phpmyadmin") ? "pma" : "phpmyadmin";
    if (cfg.sites.some((s) => s.name === name)) throw new Error(`A site named "${name}" already exists`);
    site = { name, path: dir, docroot: "", https: false };
    cfg.sites.push(site);
  }
  return site;
}

async function installPma(cfg: Config, dir: string): Promise<void> {
  {
    const zip = join(tmpDir(cfg.root), "phpmyadmin-latest.zip");
    const stage = join(tmpDir(cfg.root), "phpmyadmin-stage");
    mkdirSync(tmpDir(cfg.root), { recursive: true });
    await download(URL, zip);
    rmSync(stage, { recursive: true, force: true });
    await unzip(zip, stage);
    // the zip holds one folder, phpMyAdmin-<version>-english
    const inner = readdirSync(stage, { withFileTypes: true }).filter((d) => d.isDirectory());
    const src = inner.length === 1 && !existsSync(join(stage, "index.php")) ? join(stage, inner[0]!.name) : stage;
    if (!existsSync(join(src, "index.php"))) throw new Error("phpMyAdmin archive: index.php not found");
    rmSync(dir, { recursive: true, force: true });
    mkdirSync(join(dir, ".."), { recursive: true });
    renameSync(src, dir);
    rmSync(stage, { recursive: true, force: true });
    rmSync(zip, { force: true });
  }
}
